"""Combine source and cost evidence with explicit conservative lineage grouping."""
import collections
import csv
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
FAMILIES={'SHOTCUT-PROXY-GUIDE':'SC-CODEBASE',
          'MUSESCORE3-HANDBOOK':'MS-CODEBASE',
          'SIGIL-USER-GUIDE':'SG-CODEBASE'}

def csv_read(path):
    with path.open(newline='') as f:return list(csv.DictReader(f))

def main():
    rows=[]
    for filename in ('recruitment-sources.jsonl','root-sources.jsonl','postseal-sources.jsonl'):
        rows.extend(json.loads(x) for x in (ROOT/'evidence'/filename).read_text().splitlines())
    assert len({x['id'] for x in rows})==len(rows)
    named=set();families=set()
    for r in rows:
        work=r['independent_work_id'];family=FAMILIES.get(work,work)
        r['conservative_lineage_id']=family
        if 'retrieved_utc' in r:
            r['utc']={'retrieved':r.pop('retrieved_utc'),'basis':r.pop('utc_basis','as recorded')}
        if r.get('source_kind') is None:r['source_kind']='primary_document'
        if isinstance(r['local_receipt'],str):
            r['local_receipt']=[r['local_receipt'].split('#')[0],'reading/NOTES.jsonl','reading/CACHE_RETENTION.json']
            r['retained_full_text']=False
            r['raw_hash_recomputable_from_retained_files']=False
        eligible=r['core20_eligible']
        r['named_work_units']=int(eligible and work not in named)
        r['counted_work_units']=int(eligible and family not in families)
        r.pop('independent_work_contribution',None)
        r['count_eligibility']={'eligible':eligible,'named_contribution':r['named_work_units'],
            'contribution':r['counted_work_units'],
            'rule':'counted_work_units counts conservative_lineage_id once; named_work_units separately counts independent_work_id once. All three target manuals are grouped consistently with their target codebase. See evidence/COUNTING.md.'}
        if eligible:named.add(work);families.add(family)
    assert len(named)==24 and len(families)==21
    (ROOT/'SOURCES.jsonl').write_text(''.join(json.dumps(x,ensure_ascii=False)+'\n' for x in rows))
    post=csv_read(ROOT/'evidence/POSTSEAL_COSTS.csv');post_ids={x['id'] for x in post}
    costs=[x for x in csv_read(ROOT/'COSTS.csv') if x['id'] not in post_ids and x['id']!='AUXILIARY-EXECUTION']
    for r in costs:
        external=r['unit']=='external read requests'
        r['aggregation_role']='base additive component' if external else 'local or unknown component'
        r['matched_root_cost_id']=''
        r['incremental_request_attempts_to_existing_root']=r['count'] if external else '0'
        r['project']=r.get('project','')
    costs.extend(post)
    aux=json.loads((ROOT/'evidence/auxiliary/observed-run-20261123/receipt.json').read_text())
    costs.append(dict(id='AUXILIARY-EXECUTION',actor='auxiliary_probe',phase='postseal research probe',unit='recorded supervisor run',count='1',
        count_status='actual execution, worker and supervisor exit0',excerpt_characters='',packet_characters='',common_characters='',
        additional_work='SC sampled-hash and candidate predicate replays; five actual SG XHTML fixtures; no target application run',
        elapsed_seconds='',elapsed_status='receipt UTC interval; not developer work time',money='no paid API',
        receipt='evidence/auxiliary/observed-run-20261123/receipt.json',limitation='5/9 input predicates only; complete frozen workflows0/9; generated bytes are not valid video',
        project='SC;SG',aggregation_role='nonexternal local observation',matched_root_cost_id='',incremental_request_attempts_to_existing_root='0'))
    fields=list(dict.fromkeys(k for r in costs for k in r))
    with (ROOT/'COSTS.csv').open('w',newline='') as f:
        w=csv.DictWriter(f,fieldnames=fields);w.writeheader();w.writerows(costs)
    reported=sum(int(x['incremental_request_attempts_to_existing_root'] or 0) for x in costs)
    incomplete=sum(int(x['incremental_request_attempts_to_existing_root'] or 0) for x in costs if x['id']=='POST-SG-WEB')
    tests=csv_read(ROOT/'TESTS.csv');views=csv_read(ROOT/'VIEWS.csv');frame=csv_read(ROOT/'FRAME.csv')
    counts=dict(source_records=len(rows),named_original_works=len(named),conservative_original_lineages=len(families),
        work_families=FAMILIES,eligible_named_work_ids=sorted(named),eligible_conservative_ids=sorted(families),
        source_kinds=dict(collections.Counter(x['source_kind'] for x in rows)),frame_rows=len(frame),
        primary_cases=0,primary_denominator=3,auxiliary_cases=3,initial_body_revisions_confirmed=0,
        target_support_named_works=6,target_support_conservative_lineages=4,
        target_support_contemporary_conservative_lineages=3,target_support_required=6,
        same_domain_named_works=3,provided_external_named_works=3,counterexample_named_works=9,
        frozen_cases=len(tests),target_executed=sum(int(x['target_executed_contribution']) for x in tests),
        auxiliary_predicate_cases=sum(int(x['auxiliary_predicate_case_contribution']) for x in tests),
        complete_auxiliary_workflows=sum(int(x['auxiliary_complete_case_contribution']) for x in tests),
        views=len(views),chosen_predictions=18,candidate_case_predictions=39,
        core_choice_changes=0,technical_comparison_denominator=3,causal_effect_denominator=0,
        source_excerpt_characters={v:sum(int(x['actual_excerpt_characters']) for x in views if x['view']==v) for v in ('A','B')},
        recorded_external_request_components_excluding_partially_logged_web=reported-incomplete,
        reported_external_request_components_including_partially_logged_web=reported,
        global_cost_complete=False,status='PARTIAL')
    assert counts['frozen_cases']==9 and counts['target_executed']==0 and counts['auxiliary_predicate_cases']==5
    (ROOT/'evidence/COUNTS.json').write_text(json.dumps(counts,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps({k:counts[k] for k in ['source_records','named_original_works','conservative_original_lineages','frozen_cases','target_executed','auxiliary_predicate_cases','reported_external_request_components_including_partially_logged_web']}))

if __name__=='__main__':main()
