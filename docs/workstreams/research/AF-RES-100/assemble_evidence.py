"""Rebuild source accounting and post-outcome tables from committed ledgers.

No network, no external-program execution, and no changes to sealed judgments.
"""
from pathlib import Path
from collections import Counter, defaultdict
import argparse, csv, io, json
from urllib.parse import urldefrag

ROOT=Path(__file__).resolve().parent
SEAL2='5d81bcbeb5f1248fc1dd2ce2d825cf6467353673'

def jl(p):
    return [json.loads(x) for x in p.read_text().splitlines() if x.strip()]

def js(x): return json.dumps(x,ensure_ascii=False)
def jlines(x): return ''.join(js(r)+'\n' for r in x)

def ranges(rs):
    out=[]
    for r in sorted(rs,key=lambda x:(x['char_start'],x['char_end'])):
        d={k:r[k] for k in ['char_start','char_end','byte_start','byte_end','line_start','line_end'] if k in r}
        if d not in out:out.append(d)
    return out

def normal_source(r, origin):
    d=dict(r)
    d['q_numbers']=d.get('q_numbers',d.get('Q',['Q7']))
    d['direct_url']=d.get('direct_url',d.get('url'))
    d['fixed_url']=d.get('fixed_url') or d['direct_url']
    d['version']=d.get('version',d.get('version_section',f'post-seal2 {SEAL2}'))
    d['exact_section_payload']=d.get('exact_section_payload',{
        'identifier':d.get('payload_identifier',d.get('section')),
        'body_range':d.get('body_range'), 'version_section':d.get('version_section')})
    d['confirmed']=d.get('confirmed',d.get('observed'))
    d['count_minimum']=bool(d.get('count_minimum',d.get('count_in_minimum',False)))
    d['count_group']=d.get('count_group',d.get('category','post_outcome'))
    d['research_phase']=d.get('research_phase',d.get('phase','post-seal2'))
    d['duplicate_reason']=d.get('duplicate_reason','One canonical document/revision counted once; repeated opening is not a new primary source.')
    d['origin_ledger']=origin
    return d

def build():
    proto=json.loads((ROOT/'protocol.json').read_text())
    packets=jl(ROOT/'packets.jsonl')
    inventory={d['file_id']:d for d in jl(ROOT/'corpus-files.jsonl')}
    notes=json.loads((ROOT/'evidence/source-notes.json').read_text())
    opened=defaultdict(lambda:{'initial':[],'audit':[],'post':[],'times':[],'packets':set(),'cases':set()})
    packet_map={p['packet_id']:p for p in packets}
    for f in sorted((ROOT/'evidence/packet-access').glob('*.jsonl')):
        for e in jl(f):
            if not e.get('displayed_segments'):continue
            d=opened[e['file_id']];d['initial']+=e['displayed_segments'];d['times'].append(e['finished_utc'])
            d['packets'].add(e['packet_id']);d['cases'].add(packet_map[e['packet_id']]['case_id'])
    for e in jl(ROOT/'evidence/audit/availability-access.jsonl'):
        d=opened[e['file_id']];d['audit']+=e['segments'];d['times'].append(e['recorded_utc'])
    for e in jl(ROOT/'evidence/supplemental/reads.jsonl'):
        if not e.get('segments'):continue
        d=opened[e['file_id']];d['post']+=e['segments'];d['times'].append(e['checked_utc'])
    assert set(opened)<=set(notes),set(opened)-set(notes)
    sources=jl(ROOT/'evidence/recruitment-sources.jsonl')
    publishers={'JQ':'jqlang/jq contributors','PD':'John MacFarlane and Pandoc contributors',
                'SED':'GNU sed / Free Software Foundation','WT':'Microsoft Terminal contributors',
                'AWS':'Amazon Web Services, aws-cli','KN':'Yihui Xie and knitr contributors','CE':'CeTZ package contributors'}
    for fid in sorted(opened):
        f=inventory[fid];o=opened[fid];n=notes[fid]
        lineage='Official versioned project file; archive member '+f['path']
        if fid=='SED-0022':lineage+='; NetBSD/Berkeley original test adapted by GNU sed, identified in file header'
        if fid=='JQ-0072':lineage+='; generated by GNU Bison3.8.2, not an independent source-level test'
        if fid=='JQ-0016':lineage+='; vendored IBM/Mike Cowlishaw decNumber module'
        if fid=='CE-0004':lineage+='; file states some functions port Pomax/bezierjs'
        sources.append({'source_id':'CORPUS-'+fid,'q_numbers':['Q3','Q4','Q5','Q6'] if o['initial'] else ['Q7'],
                        'case_id':sorted(o['cases']) or ['P1' if fid.startswith('KN') else 'P4'],
                        'direct_url':f['archive_url'],'fixed_url':f['url'],'checked_utc':min(o['times']),
                        'author_publisher':publishers[f['label']],'lineage':lineage,'version':f['version'],
                        'exact_section_payload':{'archive_member':f['path'],
                            'initial_packet_displayed_ranges':ranges(o['initial']),
                            'pre_outcome_audit_displayed_ranges':ranges(o['audit']),
                            'post_outcome_displayed_ranges':ranges(o['post']),
                            'packet_ids':sorted(o['packets']),
                            'range_units':'zero-based half-open Unicode codepoints and original UTF8 bytes; lines1-based'},
                        'body_sha256':f['sha256'],'confirmed':n['confirmed'],
                        'supports':'Bounded source availability, displaced/added evidence and limits; supplemental sections do not revise sealed judgments.',
                        'limits':[n['limits'],'Reading counts refer to displayed regions, not exhaustive human attention or an executed original request.'],
                        'count_minimum':n['count_minimum'],'count_group':n['core_group'],
                        'duplicate_reason':'One fixed file counted once across A/B/F/S. Additional openings/citations and archive transport are not additional sources.',
                        'research_phase':'initial packet reading and separately labelled pre/post audits' if o['initial'] else 'post-seal2 upstream fixture',
                        'origin_ledger':'evidence/packet-access + evidence/audit/availability-access.jsonl + evidence/supplemental/reads.jsonl'})
    for rel in ['evidence/outcomes/jq/sources.jsonl','evidence/outcomes/pandoc/sources.jsonl','evidence/crossdomain/sources.jsonl']:
        for r in jl(ROOT/rel):sources.append(normal_source(r,rel))
    assert len({s['source_id'] for s in sources})==len(sources),'duplicate source IDs'
    canonical={}
    for s in sources:
        key=(urldefrag(s['fixed_url'])[0],s.get('body_sha256'))
        s['canonical_source_id']=canonical.setdefault(key,s['source_id'])
        if s['canonical_source_id']!=s['source_id']:
            s['count_minimum']=False
            s['duplicate_reason']+=' Same canonical URL/body as '+s['canonical_source_id']+'.'
    outcomes=[]
    for family in ['jq','pandoc']:
        for r in jl(ROOT/f'evidence/outcomes/{family}/outcomes.jsonl'):
            jq=family=='jq'
            first=r.get('first_visible_answer_id') if jq else (r.get('first_answer') or {}).get('answer_id')
            discussion=(r.get('asker_comment_within30d',False) or r.get('asker_self_answer_within30d',False)) if jq else r.get('asker_substantive_followup_within_30d',False)
            edits=r.get('asker_question_edit_within30d',False) if jq else bool(r.get('asker_edits_within_30d'))
            exact=r.get('strict_same_version_input_output_execution_confirmed',False) if jq else r.get('exact_user_execution',False)
            outcomes.append({'case_id':r['case_id'],'question_id':r['question_id'],
                             'current_answer_count':len(r['answers']) if jq else r['current_answer_count'],
                             'first_visible_answer_id':first,'current_accepted_answer_id':r['current_accepted_answer_id'],
                             'acceptance_event_time':'unknown; current snapshot only',
                             'asker_discussion_or_selfanswer_30d':discussion,'asker_question_edit_30d':edits,
                             'asker_either_30d':discussion or edits,'exact_original_execution_confirmed':exact,
                             'summary':r.get('execution_attribution','') if jq else r['summary'],
                             'execution_attribution':r.get('execution_attribution',r.get('execution_status')),
                             'returned_links':r['returned_links'],'failure_condition':r.get('failure_condition',r.get('return_failure_condition')),
                             'views':r.get('views',r.get('perspectives')),
                             'source_ledger':f'evidence/outcomes/{family}/outcomes.jsonl',
                             'first_outcome_access_utc':r.get('first_post_outcome_access_utc',r.get('first_outcome_access_utc')),
                             'initial_judgments_changed':False,'seal2_sha':SEAL2})
    outcomes.sort(key=lambda r:r['case_id']);assert len(outcomes)==8
    assert all(len(r['returned_links'])<=2 for r in outcomes)
    flat=[]
    for r in outcomes:
        flat.append({k:js(v) if isinstance(v,(dict,list)) else v for k,v in r.items()})
    stream=io.StringIO(newline='');w=csv.DictWriter(stream,fieldnames=list(flat[0]));w.writeheader();w.writerows(flat)
    counted=[s for s in sources if s['count_minimum']]
    summary={'source_rows':len(sources),'counted_unique_primary_sources':len(counted),
             'counted_by_group':dict(Counter(s['count_group'] for s in counted)),
             'counted_source_ids':[s['source_id'] for s in counted],
             'canonical_document_payloads':len(canonical),
             'post_outcome_rows_excluded_from_minimum':sum('outcomes/' in s.get('origin_ledger','') and not s['count_minimum'] for s in sources),
             'original_question_recruitment_sources':len(jl(ROOT/'evidence/recruitment-sources.jsonl')),
             'opened_fixed_corpus_files':len(opened),
             'note':'Minimum accounting uses8selected original questions,5main,5adjacent,4original tests and designated crossdomain pairs. Extra real reads are logged but do not inflate the quota.'}
    outcome_summary={'questions':len(outcomes),'visible_answers':sum(r['current_answer_count'] for r in outcomes),
                     'questions_with_answers':sum(r['current_answer_count']>0 for r in outcomes),
                     'currently_accepted_questions':sum(r['current_accepted_answer_id'] is not None for r in outcomes),
                     'asker_discussion_or_selfanswer_30d':sum(r['asker_discussion_or_selfanswer_30d'] for r in outcomes),
                     'asker_question_edit_30d':sum(r['asker_question_edit_30d'] for r in outcomes),
                     'asker_either_30d':sum(r['asker_either_30d'] for r in outcomes),
                     'exact_original_execution_confirmed':sum(r['exact_original_execution_confirmed'] for r in outcomes),
                     'runtime_A_B_comparable_pairs':0,
                     'limits':'Absence of a complete public execution receipt is unknown, not user failure; current acceptance has no dated history.'}
    return {'sources.jsonl':jlines(sources),'outcomes.csv':stream.getvalue(),
            'evidence/normalized-outcomes.jsonl':jlines(outcomes),
            'evidence/source-summary.json':json.dumps(summary,ensure_ascii=False,indent=2)+'\n',
            'evidence/outcome-summary.json':json.dumps(outcome_summary,ensure_ascii=False,indent=2)+'\n'},summary,outcome_summary

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--check',action='store_true');a=ap.parse_args()
    files,s,o=build()
    for rel,body in files.items():
        if a.check:assert (ROOT/rel).read_bytes()==body.encode(),'reconstruction mismatch '+rel
        else:(ROOT/rel).write_bytes(body.encode())
    print(json.dumps({'status':'PASS','source_accounting':s,'outcomes':o},ensure_ascii=False,indent=2))

if __name__=='__main__':main()
